"""Candidate normalizer for Mochipoyo full/minimal scanner comparison.

This module does not generate trade signals.  Its job is to normalize candidate
rows produced by different scanner paths into one stable schema so the upcoming
full strict scan vs minimal scan comparison can compare like-for-like rows.

Design rules:
- Do not change signal logic here.
- Do not filter by source_filter_name here.
- Do not send Discord messages here.
- payload_key is generated by mochipoyo_payload_key.py only.
- risk OK/NG split is a mechanical split on normalized risk_status.
"""
