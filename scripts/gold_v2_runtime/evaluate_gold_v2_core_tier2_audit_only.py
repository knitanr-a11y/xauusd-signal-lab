"""
GOLD V2 Core/Tier2 audit-only evaluator.

This script does NOT call AI APIs, Discord, MT5 order APIs, or any live hooks.
It only reads prebuilt GOLD V2 cluster ledgers and re-scores the frozen policy:

    Core  = fold4_rules + ABC entry gate + CAP5 sizing
    Tier2 = Core REJECT rows where trend_eff96 <= 0.4 and ret96 <= -25, CAP3 sizing

It also evaluates an adaptive Tier2 gate:

    Allow Tier2 only when the number of Core signals in the previous N business
    days is below a configurable threshold.  Default: previous 10 business days
    Core count < 5.

Inputs expected by default:

    <input-dir>/abc_stack_cap_2025_fold4_cluster_ledger.csv
    <input-dir>/abc_stack_cap_2026_cluster_ledger.csv

These are generated by the prior stack-cap validation workflow.  The script is
kept intentionally separate from candle generation/re-exploration so it can be
rerun safely and deterministically on the same candidate universe.

No optional markdown dependencies are required.  In particular, this file does
not use pandas.DataFrame.to_markdown(), because that requires the optional
`tabulate` package.
"""

from __future__ import annotations

