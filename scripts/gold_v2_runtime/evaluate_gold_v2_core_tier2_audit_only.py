def json_safe_records(df: pd.DataFrame) -> List[Dict[str, object]]:
    safe = df.replace({np.nan: None, np.inf: "inf", -np.inf: "-inf"})
    return safe.to_dict(orient="records")


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    input_dir = Path(args.input_dir).expanduser().resolve() if args.input_dir else default_input_dir()
    output_dir = Path(args.output_dir).expanduser().resolve() if args.output_dir else default_output_dir()
    output_dir.mkdir(parents=True, exist_ok=True)

    inputs = [
        ("2025_fold4", input_dir / "abc_stack_cap_2025_fold4_cluster_ledger.csv"),
        ("2026_WF", input_dir / "abc_stack_cap_2026_cluster_ledger.csv"),
    ]

    dataframes: List[pd.DataFrame] = []
    audits: List[InputAudit] = []
    for dataset, path in inputs:
        df, audit = read_cluster_ledger(path, dataset)
        audits.append(audit)
        if audit.status == "OK":
            dataframes.append(df)
        print(f"[INPUT] {dataset}: status={audit.status} rows={audit.rows} path={path}")
        if audit.message:
            print(f"        {audit.message}")

    if args.strict and any(a.status != "OK" for a in audits):
        print("[ERROR] Strict mode: input audit failed", file=sys.stderr)
        return 2
    if not dataframes:
        print("[ERROR] No valid input ledgers loaded", file=sys.stderr)
        return 2

    portfolio_parts = [
        build_portfolio(
            df,
            args.tier2_trend_eff96_max,
            args.tier2_ret96_max,
            args.adaptive_tier2_lookback_business_days,
            args.adaptive_tier2_core_threshold,
        )
        for df in dataframes
    ]
    portfolio = pd.concat(portfolio_parts, ignore_index=True) if portfolio_parts else pd.DataFrame()
    portfolio = sort_columns(portfolio)

    aggregate = summarize_aggregate(portfolio)
    monthly = summarize_monthly(portfolio)
    signal = summarize_signal(portfolio)

    portfolio.to_csv(output_dir / "core_tier2_portfolio_ledger.csv", index=False, encoding="utf-8-sig")
    aggregate.to_csv(output_dir / "core_tier2_aggregate_summary.csv", index=False, encoding="utf-8-sig")
    monthly.to_csv(output_dir / "core_tier2_monthly_summary.csv", index=False, encoding="utf-8-sig")
    signal.to_csv(output_dir / "core_tier2_signal_breakdown.csv", index=False, encoding="utf-8-sig")
    pd.DataFrame([asdict(a) for a in audits]).to_csv(output_dir / "core_tier2_input_audit.csv", index=False, encoding="utf-8-sig")

    summary = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "status": "AUDIT_ONLY",
        "input_dir": str(input_dir),
        "output_dir": str(output_dir),
        "policy": {
            "core": "signal_ABC != REJECT; A uses CAP5; B/C use CAP3",
            "tier2_static": f"signal_ABC == REJECT AND trend_eff96 <= {args.tier2_trend_eff96_max} AND ret96 <= {args.tier2_ret96_max}; uses CAP3",
            "tier2_adaptive": f"tier2_static AND previous {args.adaptive_tier2_lookback_business_days} business days Core count < {args.adaptive_tier2_core_threshold}",
        },
        "input_audit": [asdict(a) for a in audits],
        "aggregate": json_safe_records(aggregate),
    }
    (output_dir / "core_tier2_summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    write_markdown_report(
        output_dir / "GOLD_V2_CORE_TIER2_AUDIT_ONLY_REPORT.md",
        aggregate,
        monthly,
        signal,
        audits,
        args.tier2_trend_eff96_max,
        args.tier2_ret96_max,
        args.adaptive_tier2_lookback_business_days,
        args.adaptive_tier2_core_threshold,
    )

    print(f"[DONE] output_dir={output_dir}")
    print(aggregate[["dataset", "view", "count", "win_rate", "pf", "total_r", "worst", "maxdd", "core_count", "tier2_count"]].to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
